// The MOS bridge built with Gradle, for the emulator quick path (rom/emulator/README.md).
// Same Java and AIDL as the ROM build (rom/vendor-extra/MosBridge); only the manifest is
// a copy, because AGP rejects a `package` attribute that Soong requires. The APK must be
// re-signed with the emulator image's platform key (rom/emulator/install_bridge.sh).
plugins {
    id("com.android.application")
}

val certDir = file("build/generated/mos-certs")

android {
    namespace = "dev.mos.bridge"
    compileSdk = 35

    defaultConfig {
        applicationId = "dev.mos.bridge"
        minSdk = 31          // knownSigner permissions need API 31
        targetSdk = 35
        versionCode = 2
        versionName = "2"
    }

    buildFeatures {
        aidl = true
    }

    sourceSets["main"].apply {
        java.srcDir("../../rom/vendor-extra/MosBridge/src")
        aidl.srcDir("../../rom/vendor-extra/MosBridge/aidl")
        res.srcDir(certDir)
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    lint {
        // INJECT_EVENTS / WRITE_SECURE_SETTINGS are platform permissions on purpose.
        disable += setOf("ProtectedPermissions", "PrivateApi", "DiscouragedPrivateApi")
    }
}

// Pins the MOS app's signing certificate, like rom/tools/pin_cert.py does for the ROM:
//   ./gradlew :bridge:assembleRelease -Pmos.appCertSha256=<sha256 of the app's signing cert>
// Without the property (e.g. Android Studio's "Make Project") it pins the all-zero
// placeholder, which no app matches: the bridge then refuses every caller.
val generateKnownCerts = tasks.register("generateKnownCerts") {
    val digest = providers.gradleProperty("mos.appCertSha256")
    inputs.property("digest", digest.orElse(""))
    outputs.dir(certDir)
    doLast {
        val given = digest.orNull?.lowercase()?.removePrefix("sha256:")?.replace(":", "")?.trim()
        if (given == null) logger.warn("mos.appCertSha256 not set: this bridge build trusts no app")
        val d = given ?: "0".repeat(64)
        require(Regex("[0-9a-f]{64}").matches(d)) { "not a SHA-256 digest: $d" }
        require(given == null || d != "0".repeat(64)) { "the all-zero digest is the refuse-everyone placeholder" }
        val values = File(certDir, "values").apply { mkdirs() }
        File(values, "known_certs.xml").writeText(
            """
            |<?xml version="1.0" encoding="utf-8"?>
            |<!-- Generated by android/bridge/build.gradle.kts; do not edit. -->
            |<resources>
            |    <string-array name="mos_known_certs">
            |        <item>$d</item>
            |    </string-array>
            |</resources>
            |""".trimMargin(),
        )
    }
}
tasks.named("preBuild") { dependsOn(generateKnownCerts) }
