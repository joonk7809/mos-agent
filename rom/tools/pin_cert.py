"""Pin the MOS app's signing certificate into the bridge's knownCerts resource.

    python3 rom/tools/pin_cert.py DIGEST OUT_XML

DIGEST is the SHA-256 of the app's signing certificate, in any common spelling
(`keytool -list -v` prints `AB:CD:...`, `sha256sum` prints lowercase hex). The bridge
grants dev.mos.permission.BRIDGE only to apps signed with a certificate listed here.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

_HEX64 = re.compile(r"[0-9a-f]{64}")
_PLACEHOLDER = "0" * 64


def normalize_digest(raw: str) -> str:
    """Return the digest as 64 lowercase hex chars, or raise ValueError."""
    s = raw.strip().lower()
    if s.startswith("sha256:") or s.startswith("sha-256:"):
        s = s.split(":", 1)[1].strip()
    s = s.replace(":", "").replace(" ", "")
    if not _HEX64.fullmatch(s):
        raise ValueError(f"not a SHA-256 hex digest: {raw!r}")
    if s == _PLACEHOLDER:
        raise ValueError("refusing the all-zero placeholder digest")
    return s


def known_certs_xml(digest: str) -> str:
    d = normalize_digest(digest)
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by rom/tools/pin_cert.py; do not edit. -->\n"
        "<resources>\n"
        '    <string-array name="mos_known_certs">\n'
        f"        <item>{d}</item>\n"
        "    </string-array>\n"
        "</resources>\n"
    )


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    try:
        xml = known_certs_xml(argv[1])
    except ValueError as e:
        print(f"pin_cert: {e}", file=sys.stderr)
        return 1
    Path(argv[2]).write_text(xml)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
